/**
 * 5×7 点阵字库（`P-B15` 教学素材的图片生成用，2026-09-23）。
 *
 * ### 为什么要有自己的字库
 *
 * 教学素材里的图片**必须有标注**，否则一张只有曲线的图谁也说不清哪条是切线。
 * 而在这个仓库里画字只有两条路：
 *   1. 引一个图形库（`canvas` / `sharp` / `jimp`）—— 要装原生依赖，
 *      为了三张示意图给整个项目加构建负担，不划算（`I39` 锁文件问题还在）；
 *   2. **自带点阵字库** —— 就是本文件：不到 60 行数据，零依赖，输出确定。
 *
 * ### 只用大写与 ASCII
 *
 * 点阵字库做不了汉字（一个汉字 16×16 起，且要背几千个位图）。
 * 所以图片里的标注**一律用 ASCII 大写**（`F(X)=X^2`、`SECANT`），
 * 中文说明放在同目录的 `.md` 题注里 —— 图片是**示意图**，题注才是讲解。
 * 这不是将就：题注与图分开，正是教材的常规做法。
 *
 * ### 位图格式
 *
 * `NAME: '第0行|第1行|…|第6行'`，每行 5 个字符，`1` 为落笔、`0` 为空。
 * 写成字符串而不是数字，是为了**能用眼睛直接校对**字母长得对不对 ——
 * 十六进制位图看错一位就会画出个怪物，而那种错很难在代码里发现。
 *
 * 缺字**抛错**而不是画空白：画空白会让一张少了标注的图静默通过所有检查
 * （与 §4.2「不得静默」同一条纪律）。
 */

