/** 字面宽度 / 高度（不含字符间距） */
export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** 字间距：留 1 列，否则 `F(X)` 会糊成一团 */
export const GLYPH_GAP = 1;

/** 把所有位图字符串预先解析成 [row][col] 的布尔表，避免每次画字都重新 split */
const GLYPHS = Object.fromEntries(
  Object.entries(RAW).map(([name, rows]) => [name, rows.split('|')]),
);

/**
 * 取一个字形的位图行。
 *
 * 小写字母**自动转大写**（`f(x)` 与 `F(X)` 是同一张图，不必再背一套小写位图）；
 * 没有对应字形的字符返回填空方框 —— 由调用方决定要不要报警，但**绝不返回空**。
 */
export function glyphFor(char) {
  const key = char.toUpperCase();
  if (Object.hasOwn(GLYPHS, key)) return GLYPHS[key];
  return GLYPHS[FALLBACK_GLYPH];
}

/** 这句话里有没有画不出来的字（供生成脚本自查，也供 verify 断言） */
export function missingGlyphs(text) {
  return [...new Set([...text].filter((char) => !Object.hasOwn(GLYPHS, char.toUpperCase())))];
}

/** 一段文字按当前 scale 画出来占多少像素（宽、高） */
export function measure(text, scale = 1) {
  const chars = [...text].length;
  if (chars === 0) return { width: 0, height: GLYPH_HEIGHT * scale };
  return {
    width: (chars * (GLYPH_WIDTH + GLYPH_GAP) - GLYPH_GAP) * scale,
    height: GLYPH_HEIGHT * scale,
  };
}
